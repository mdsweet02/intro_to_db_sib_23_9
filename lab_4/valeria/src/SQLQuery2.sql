CREATE OR ALTER VIEW vw_JournalRegistration AS
SELECT
    r.[Номер_документа],
    r.[Дата_регистрации],
    d.[Наименование] AS [Документ],
    z.[ФИО] AS [Заявитель],
    r.[Дата_исполнения_по_закону],
    st.[Наименование] AS [Статус]
FROM [Регистрация] r
JOIN [Документы] d ON r.[Код_документа] = d.[Код]
JOIN [Анкета_заявителя] z ON r.[Код_заявителя] = z.[Код_заявителя]
JOIN [Статус_документа] st ON r.[Статус] = st.[Код];