CREATE OR ALTER VIEW vw_CompletedDocsByEmployee AS
SELECT
    m.[Код_сотрудника_исполнителя] AS [ИсполнительID],
    e.[ФИО] AS [Исполнитель],
    r.[Номер_документа],
    d.[Наименование] AS [Документ],
    m.[Дата_окончания_исполнения]
FROM [Движение] m
JOIN [Сотрудники] e ON m.[Код_сотрудника_исполнителя] = e.[Код]
JOIN [Регистрация] r ON m.[Код_документа] = r.[Номер_документа]
JOIN [Документы] d ON r.[Код_документа] = d.[Код]
WHERE m.[Дата_окончания_исполнения] IS NOT NULL;
GO