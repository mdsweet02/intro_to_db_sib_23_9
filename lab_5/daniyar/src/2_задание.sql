CREATE PROCEDURE dbo.процедура_2
    @Код_типа_категории_проекта INT   -- параметр: код категории
AS
BEGIN
    SET NOCOUNT ON;

    SELECT
        Код_студента,
        Код_преподавателя_руководителя,
        Тема_дипломного_проекта,
        Код_типа_категории_проекта,
        Код_рецензента
    FROM dbo.Проект
    WHERE Код_типа_категории_проекта = @Код_типа_категории_проекта;
END;
GO
