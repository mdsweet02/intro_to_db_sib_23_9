CREATE FUNCTION dbo.ф_студенты_группы
(
    @код_группы NVARCHAR(100)
)
RETURNS TABLE
AS
RETURN
(
    SELECT
        [Код_студента],
        [ФИО],
        [код_группы],
        [код_специальности],
        [средний_балл_успеваемости]
    FROM dbo.Студенты
    WHERE [код_группы] = @код_группы
);
GO
