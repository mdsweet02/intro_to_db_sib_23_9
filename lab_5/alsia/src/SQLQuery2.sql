SELECT 
    Договора.Номер_договора,
    Клиенты.ФИО_Наименование AS Клиент,
    Виды_страхования.Наименование AS [Вид страхования],
    Страховщики.ФИО AS Страховщик,
    Договора.Дата_заключения,
    Договора.Срок_действия,
    Договора.Сумма_страховки,
    Договора.Месячный_взнос,
    Договора.Накопленная_сумма
FROM Договора
JOIN Клиенты 
    ON Договора.ИИН_БИН = Клиенты.ИИН_БИН
JOIN Виды_страхования 
    ON Договора.Код_вида = Виды_страхования.Код_вида
JOIN Страховщики 
    ON Договора.Код_страховщика = Страховщики.Код_страховщика
WHERE Договора.Номер_договора = 1; 

