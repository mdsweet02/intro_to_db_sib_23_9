SELECT 
    Клиенты.ИИН_БИН,
    Клиенты.ФИО_Наименование AS [Наименование клиента],
    Районы.Наименование AS [Район],
    Клиенты.Адрес,
    Клиенты.Телефон
FROM Клиенты
JOIN Районы 
    ON Клиенты.Код_района = Районы.Код_района
WHERE Клиенты.Признак_клиента = 'юридическое лицо'
ORDER BY Клиенты.ФИО_Наименование;

