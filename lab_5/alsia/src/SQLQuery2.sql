SELECT 
    Договора.Номер_договора,
    Клиенты.ФИО_Наименование AS Клиент,
    Договора.Дата_заключения,
    Договора.Срок_действия,
    DATEADD(MONTH, DATEDIFF(MONTH, 0, Договора.Срок_действия), 0) AS [Дата окончания],
    Договора.Сумма_страховки
FROM Договора
JOIN Клиенты 
    ON Договора.ИИН_БИН = Клиенты.ИИН_БИН
WHERE MONTH(DATEADD(MONTH, DATEDIFF(MONTH, 0, Договора.Срок_действия), 0)) = 12
  AND YEAR(DATEADD(MONTH, DATEDIFF(MONTH, 0, Договора.Срок_действия), 0)) = YEAR(GETDATE())
ORDER BY [Дата окончания];

