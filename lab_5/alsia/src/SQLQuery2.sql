SELECT DISTINCT 
    Банки.Наименование AS [Банк],
    Банки.Адрес
FROM Банки
JOIN Клиенты 
    ON Банки.Код_банка = Клиенты.Код_банка
JOIN Договора 
    ON Клиенты.ИИН_БИН = Договора.ИИН_БИН
WHERE DAY(Договора.Дата_заключения) = 15
  AND YEAR(Договора.Дата_заключения) = YEAR(GETDATE())
ORDER BY Банки.Наименование;

