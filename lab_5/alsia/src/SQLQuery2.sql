    ON Перечисления.Код_банка = Банки.Код_банка
WHERE MONTH(Перечисления.Дата_оплаты) = MONTH(GETDATE())
  AND YEAR(Перечисления.Дата_оплаты) = YEAR(GETDATE())
ORDER BY Перечисления.Дата_оплаты;

