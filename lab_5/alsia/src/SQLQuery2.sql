SELECT 
    Перечисления.Номер_договора,
    Клиенты.ФИО_Наименование AS Клиент,
    Банки.Наименование AS Банк,
    Перечисления.Дата_оплаты,
    CONCAT(Перечисления.Месяц, '-', Перечисления.Год) AS [Месяц и год],
    Перечисления.Сумма
FROM Перечисления
JOIN Клиенты 
    ON Перечисления.ИИН_БИН = Клиенты.ИИН_БИН
