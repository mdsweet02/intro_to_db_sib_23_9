SELECT 
    Страховщики.ФИО AS Страховщик,
    Договора.Номер_договора,
    Договора.Сумма_страховки AS [Сумма договора],
    Страховщики.Процент_вознаграждения AS [% вознаграждения],
    (Договора.Сумма_страховки * Страховщики.Процент_вознаграждения / 100) AS [Сумма вознаграждения]
FROM Договора
JOIN Страховщики 
    ON Договора.Код_страховщика = Страховщики.Код_страховщика
WHERE Страховщики.Код_страховщика = 1 
ORDER BY Договора.Номер_договора;

