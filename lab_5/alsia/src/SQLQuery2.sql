SELECT 
    Виды_страхования.Наименование AS [Вид страхования],
    SUM(Договора.Сумма_страховки) AS [Общая сумма договоров]
FROM Виды_страхования
LEFT JOIN Договора 
    ON Виды_страхования.Код_вида = Договора.Код_вида
WHERE YEAR(Договора.Дата_заключения) = YEAR(GETDATE())
GROUP BY Виды_страхования.Наименование;

